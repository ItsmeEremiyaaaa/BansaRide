// Builds src/poiData.js: real shops, hotels, food places, banks, pharmacies and gas stations inside Bansalan (OpenStreetMap).
// Run with: node scripts/build-poi.mjs   (needs internet). Only named places inside the municipal border are kept.
import { writeFileSync } from 'node:fs'
import { boundary, bounds } from '../src/boundary.js'

const inside = (lat, lon) => {
  const ring = boundary[0]
  let c = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [yi, xi] = ring[i], [yj, xj] = ring[j]
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) c = !c
  }
  return c
}
const [[s, w], [n, e]] = bounds
const bbox = `${s},${w},${n},${e}`
const query = `[out:json][timeout:90];
(
  nwr["shop"~"supermarket|convenience|general|mall|department_store|variety_store|grocery"](${bbox});
  nwr["tourism"~"hotel|guest_house|motel|hostel|resort|apartment"](${bbox});
  nwr["amenity"~"restaurant|fast_food|cafe|bank|atm|pharmacy|fuel"](${bbox});
);
out center tags;`

// the public servers are busy at times, so try several, a few times each
const SERVERS = ['https://overpass-api.de/api/interpreter', 'https://overpass.kumi.systems/api/interpreter', 'https://overpass.private.coffee/api/interpreter']
let j = null
for (let round = 0; round < 3 && !j; round++) {
  for (const url of SERVERS) {
    try {
      const res = await fetch(url, { method: 'POST', body: 'data=' + encodeURIComponent(query), headers: { 'User-Agent': 'BansaRide-dev/0.1 (local project)', 'Content-Type': 'application/x-www-form-urlencoded' } })
      const text = await res.text()
      j = JSON.parse(text)
      console.log('got data from', url)
      break
    } catch { console.log('busy:', url) }
  }
  if (!j) await new Promise((r) => setTimeout(r, 8000))
}
if (!j) throw new Error('No server answered. Try again in a few minutes.')

const kindOf = (t) => {
  if (t.tourism) return 'Hotel'
  if (/supermarket|convenience|general|mall|department_store|variety_store|grocery/.test(t.shop ?? '')) return 'Store'
  if (/restaurant|fast_food|cafe/.test(t.amenity ?? '')) return 'Food'
  if (/bank|atm/.test(t.amenity ?? '')) return 'Bank'
  if (t.amenity === 'pharmacy') return 'Pharmacy'
  if (t.amenity === 'fuel') return 'Gas'
  return null
}
const slug = (x) => x.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const seen = new Set()
const out = []
for (const el of j.elements) {
  const t = el.tags ?? {}
  const name = t.name ?? t.brand ?? t.operator
  const lat = el.lat ?? el.center?.lat, lon = el.lon ?? el.center?.lon
  const kind = kindOf(t)
  if (!name || !kind || lat == null || !inside(lat, lon)) continue
  let id = `poi-${slug(name)}`
  while (seen.has(id)) id += '-2'
  seen.add(id)
  const note = [t['addr:street'], t['addr:suburb'] ?? t['addr:barangay'], t.opening_hours ? `Open ${t.opening_hours}` : ''].filter(Boolean).join(' · ')
  out.push({ id, name, kind, sub: t.shop ?? t.tourism ?? t.amenity, lat: Number(lat.toFixed(5)), lon: Number(lon.toFixed(5)), note })
}
out.sort((a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name))
const count = out.reduce((m, p) => ((m[p.kind] = (m[p.kind] ?? 0) + 1), m), {})
console.log(count)
console.log(out.filter((p) => /7.?eleven|puregold|robinson|savemore|gaisano|hotel|inn|lodge|resort/i.test(p.name)).map((p) => `${p.kind}: ${p.name}`).join('\n'))
writeFileSync(new URL('../src/poiData.js', import.meta.url),
  `// GENERATED by scripts/build-poi.mjs. Places © OpenStreetMap contributors (ODbL). Only named places inside Bansalan.\nexport const geoPois = ${JSON.stringify(out, null, 1)}\n`)
console.log('wrote', out.length, 'places')
