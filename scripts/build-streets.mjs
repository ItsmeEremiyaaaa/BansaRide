// Builds src/streetsData.js: every named street inside the Bansalan border (OpenStreetMap) with a real road route
// from the Bus Terminal to the part of the street nearest to it (OSRM). Needs internet. Run: node scripts/build-streets.mjs
import { writeFileSync } from 'node:fs'
import { boundary } from '../src/boundary.js'

const UA = { 'User-Agent': 'BansaRide-dev/0.1 (local project)' }
const TERMINAL = { lat: 6.78732, lon: 125.21218 }
// Local names people use for a street (OpenStreetMap name -> local name).
const LOCAL = { 'Dama de Noche Street': { name: 'Curvada Street', also: 'Dama de Noche Street' } }
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const inside = (pt, ring) => { let c = false; for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) { const [yi, xi] = ring[i], [yj, xj] = ring[j]; if ((yi > pt[0]) !== (yj > pt[0]) && pt[1] < ((xj - xi) * (pt[0] - yi)) / (yj - yi) + xi) c = !c } return c }
const dist = (a, b) => Math.hypot((a.lat - b.lat) * 111, (a.lon - b.lon) * 110)

const q = `[out:json][timeout:120];way["highway"~"^(primary|secondary|tertiary|unclassified|residential|living_street|service|trunk)$"]["name"](6.72,125.15,6.99,125.28);out center tags;`
let els
for (let i = 0; i < 4 && !els; i++) {
  const r = await fetch('https://overpass-api.de/api/interpreter', { method: 'POST', headers: { ...UA, Accept: 'application/json', 'Content-Type': 'application/x-www-form-urlencoded' }, body: 'data=' + encodeURIComponent(q) })
  const t = await r.text()
  try { els = JSON.parse(t).elements } catch { await sleep(8000) }
}
if (!els) throw new Error('Overpass did not answer')

// one entry per street name: the segment nearest to the terminal
const best = new Map()
for (const e of els) {
  const c = { lat: e.center.lat, lon: e.center.lon }
  if (!inside([c.lat, c.lon], boundary[0])) continue
  const n = e.tags.name
  const d = dist(c, TERMINAL)
  if (!best.has(n) || d < best.get(n).d) best.set(n, { ...c, d, hw: e.tags.highway })
}
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const streets = [...best.entries()].map(([osm, v]) => {
  const local = LOCAL[osm]
  return {
    id: `st-${slug(local?.name ?? osm)}`, name: local?.name ?? osm, also: local?.also ?? '', kind: 'Street',
    lat: Number(v.lat.toFixed(5)), lon: Number(v.lon.toFixed(5)),
    note: local ? `Also called ${local.also}` : (v.hw === 'primary' || v.hw === 'secondary' || v.hw === 'trunk' ? 'Main road' : 'Street in Bansalan'),
  }
}).sort((a, b) => a.name.localeCompare(b.name))

const routes = []
for (const s of streets) {
  const url = `https://router.project-osrm.org/route/v1/driving/${TERMINAL.lon},${TERMINAL.lat};${s.lon},${s.lat}?overview=full&geometries=geojson`
  let j
  for (let i = 0; i < 3 && !j; i++) {
    try { const r = await fetch(url, { headers: UA }); const x = await r.json(); if (x.code === 'Ok') j = x } catch { /* retry */ }
    if (!j) await sleep(2500)
  }
  if (!j) { console.log('NO ROUTE', s.name); continue }
  const leg = j.routes[0]
  const km = Math.round(leg.distance / 100) / 10
  routes.push({
    id: `terminal-${s.id}`, from: 'terminal', to: s.id, vehicle: 'Tricycle', km,
    minutes: Math.max(2, Math.round((km / 20) * 60) + 1),
    path: leg.geometry.coordinates.map(([lon, lat]) => [Number(lat.toFixed(4)), Number(lon.toFixed(4))]),
  })
  console.log(s.name.padEnd(36), String(km).padStart(5), 'km', leg.geometry.coordinates.length, 'pts')
  await sleep(1100)
}
writeFileSync(new URL('../src/streetsData.js', import.meta.url),
  `// GENERATED by scripts/build-streets.mjs. Streets © OpenStreetMap contributors (ODbL). Routes from OSRM.\nexport const geoStreets = ${JSON.stringify(streets, null, 1)}\n\nexport const geoStreetRoutes = ${JSON.stringify(routes)}\n`)
console.log('wrote', streets.length, 'streets,', routes.length, 'routes')
