// Builds src/townsData.js: other towns and cities with real road distance from the Bansalan Bus Terminal.
// Run with: node scripts/build-towns.mjs   (needs internet). Distances are real (OSRM). Travel times are estimates.
import { writeFileSync } from 'node:fs'

const FROM = { lat: 6.78732, lon: 125.21218 } // Bansalan Bus Terminal
const UA = { 'User-Agent': 'BansaRide-dev/0.1 (local project)' }
const towns = [
  ['digos', 'Digos City', 'Davao del Sur', 'Digos, Davao del Sur'],
  ['matanao', 'Matanao', 'Davao del Sur', 'Matanao, Davao del Sur'],
  ['magsaysay', 'Magsaysay', 'Davao del Sur', 'Magsaysay, Davao del Sur'],
  ['hagonoy', 'Hagonoy', 'Davao del Sur', 'Hagonoy, Davao del Sur'],
  ['padada', 'Padada', 'Davao del Sur', 'Padada, Davao del Sur'],
  ['santa-cruz', 'Santa Cruz', 'Davao del Sur', 'Santa Cruz, Davao del Sur'],
  ['kiblawan', 'Kiblawan', 'Davao del Sur', 'Kiblawan, Davao del Sur'],
  ['sulop', 'Sulop', 'Davao del Sur', 'Sulop, Davao del Sur'],
  ['kapatagan', 'Kapatagan', 'Davao del Sur', 'Kapatagan, Digos, Davao del Sur'],
  ['malalag', 'Malalag', 'Davao del Sur', 'Malalag, Davao del Sur'],
  ['davao', 'Davao City', 'Davao del Sur region', 'Davao City, Philippines'],
  ['kidapawan', 'Kidapawan City', 'Cotabato', 'Kidapawan, Cotabato'],
  ['gensan', 'General Santos City', 'South Cotabato', 'General Santos, South Cotabato'],
  ['cotabato', 'Cotabato City', 'Maguindanao', 'Cotabato City, Philippines'],
]
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const out = []
for (const [id, name, group, q] of towns) {
  const g = await (await fetch(`https://nominatim.openstreetmap.org/search?format=json&limit=1&q=${encodeURIComponent(q)}`, { headers: UA })).json()
  if (!g[0]) { console.log('NOT FOUND', name); await sleep(1200); continue }
  const lat = Number(g[0].lat), lon = Number(g[0].lon)
  await sleep(1200)
  const r = await (await fetch(`https://router.project-osrm.org/route/v1/driving/${FROM.lon},${FROM.lat};${lon},${lat}?overview=false`, { headers: UA })).json()
  if (r.code !== 'Ok') { console.log('NO ROUTE', name, r.code); await sleep(1200); continue }
  const km = Math.round(r.routes[0].distance / 100) / 10
  const car = r.routes[0].duration / 60
  // public vans and buses stop often, so we estimate about 1.4x the car time, rounded to 5 minutes
  const mins = Math.max(10, Math.round((car * 1.4) / 5) * 5)
  const duration = mins >= 60 ? `about ${Math.floor(mins / 60)} h${mins % 60 ? ` ${mins % 60} min` : ''}` : `about ${mins} min`
  out.push({ id, name, group, km, mins, duration, lat: Number(lat.toFixed(4)), lon: Number(lon.toFixed(4)), place: g[0].display_name.split(',').slice(0, 3).join(',').trim() })
  console.log(name.padEnd(22), String(km).padStart(6), 'km', duration.padEnd(16), g[0].display_name.slice(0, 70))
  await sleep(1200)
}
out.sort((a, b) => a.km - b.km)
writeFileSync(new URL('../src/townsData.js', import.meta.url),
  `// GENERATED by scripts/build-towns.mjs. Locations © OpenStreetMap contributors (ODbL). Distances from OSRM. Durations are estimates.\nexport const geoTowns = ${JSON.stringify(out, null, 1)}\n`)
console.log('wrote', out.length, 'towns')
