// Builds src/boundary.js: the real Bansalan border and its barangay names, from OpenStreetMap.
// Run with: node scripts/build-boundary.mjs   (needs internet; also needs scripts/overpass2.json from the places lookup)
import { readFileSync, writeFileSync } from 'node:fs'

const url = 'https://nominatim.openstreetmap.org/lookup?osm_ids=R14903173&format=geojson&polygon_geojson=1&polygon_threshold=0.0004'
const res = await fetch(url, { headers: { 'User-Agent': 'BansaRide-dev/0.1 (local project)' } })
const gj = await res.json()
const g = gj.features[0].geometry
const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates
// keep outer rings only, as [lat, lon]
const rings = polys.map((p) => p[0].map(([lon, lat]) => [Number(lat.toFixed(4)), Number(lon.toFixed(4))]))
rings.sort((a, b) => b.length - a.length)

const inside = (pt, ring) => {
  let c = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [yi, xi] = ring[i], [yj, xj] = ring[j]
    if ((yi > pt[0]) !== (yj > pt[0]) && pt[1] < ((xj - xi) * (pt[0] - yi)) / (yj - yi) + xi) c = !c
  }
  return c
}
const all = JSON.parse(readFileSync(new URL('./overpass2.json', import.meta.url), 'utf8')).elements
const seen = new Set()
const barangays = []
for (const e of all) {
  const t = e.tags ?? {}
  if (t.place !== 'village' || !t.name) continue
  const lat = e.lat ?? e.center?.lat, lon = e.lon ?? e.center?.lon
  if (!rings.some((r) => inside([lat, lon], r)) || seen.has(t.name)) continue
  seen.add(t.name)
  barangays.push({ name: t.name, lat: Number(lat.toFixed(5)), lon: Number(lon.toFixed(5)) })
}
barangays.sort((a, b) => a.name.localeCompare(b.name))

const lats = rings.flat().map((p) => p[0]), lons = rings.flat().map((p) => p[1])
const bounds = [[Math.min(...lats), Math.min(...lons)], [Math.max(...lats), Math.max(...lons)]]
writeFileSync(new URL('../src/boundary.js', import.meta.url),
  `// GENERATED by scripts/build-boundary.mjs. Border and barangays © OpenStreetMap contributors (ODbL).\nexport const boundary = ${JSON.stringify(rings)}\nexport const bounds = ${JSON.stringify(bounds)}\nexport const barangays = ${JSON.stringify(barangays)}\n`)
console.log('rings', rings.map((r) => r.length), 'bounds', JSON.stringify(bounds), 'barangays', barangays.length)
console.log(barangays.map((b) => b.name).join(', '))
